const mongoose = require("mongoose");

const mortalitySchema = new mongoose.Schema(
  {
    birdBatch: {
      type: String,
      required: true,
      trim: true,
    },

    // The flock whose birds were affected.
    flock: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Flock",
      default: null,
      index: true,
    },

    // Exact allocation from which the dead birds are deducted.
    allocation: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "FlockAllocation",
      default: null,
      index: true,
    },

    // Populated automatically for mortality generated by Production.
    productionRecord: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Production",
      default: null,
    },

    numberDead: {
      type: Number,
      required: true,
      min: 0,
      validate: {
        validator: Number.isInteger,
        message: "Number of dead birds must be a whole number.",
      },
    },

    birdHealthRecord: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "BirdHealth",
      default: null,
    },

    cause: {
      type: String,
      required: true,
      trim: true,
    },

    estimatedLoss: {
      type: Number,
      default: 0,
      min: 0,
    },

    notes: {
      type: String,
      default: "",
      trim: true,
    },

    date: {
      type: Date,
      default: Date.now,
    },
  },
  {
    timestamps: true,
  },
);

// Only one mortality record can belong to a production record.
mortalitySchema.index({
  productionRecord: 1,
  allocation: 1,
  date: -1,
});

// Useful for retrieving mortality records for a flock allocation.
mortalitySchema.index({
  allocation: 1,
  date: -1,
});

module.exports = mongoose.model("Mortality", mortalitySchema);
